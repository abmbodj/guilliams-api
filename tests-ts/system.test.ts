test("private message images are visible only to conversation members", async (t) => {
  const { app } = await setup(t);
  const a = await login(app),
    b = await login(app, "bob"),
    c = await login(app, "carol");
  const photo = (
    await app.inject({
      method: "POST",
      url: "/api/media/",
      headers: b,
      payload: {
        filename: "private.png",
        content_type: "image/png",
        content_base64: Buffer.from([
          137, 80, 78, 71, 13, 10, 26, 10, 0,
        ]).toString("base64"),
      },
    })
  ).json();
  assert.equal(
    (
      await app.inject({
        method: "PATCH",
        url: "/api/me/",
        headers: a,
        payload: { photo_id: photo.id },
      })
    ).statusCode,
    422,
  );
  const conv = (
    await app.inject({
      method: "POST",
      url: "/api/conversations/",
      headers: b,
      payload: { kind: "listing", listing_id: "demo-chair" },
    })
  ).json();
  assert.equal(
    (
      await app.inject({
        method: "POST",
        url: `/api/conversations/${conv.id}/messages/`,
        headers: b,
        payload: { text: "Photo", photo_id: photo.id },
      })
    ).statusCode,
    201,
  );
  assert.equal(
    (await app.inject({ method: "GET", url: photo.content_url, headers: a }))
      .statusCode,
    200,
  );
  assert.equal(
    (await app.inject({ method: "GET", url: photo.content_url, headers: c }))
      .statusCode,
    404,
  );
});

test("duplicate sponsor requests are atomic and terminal decisions stay terminal", async (t) => {
  const { app } = await setup(t);
  const a = await login(app),
    b = await login(app, "bob");
  const results = await Promise.all(
    Array.from({ length: 2 }, () =>
      app.inject({
        method: "POST",
        url: "/api/sponsorships/",
        headers: b,
        payload: { sponsor_id: "alice" },
      }),
    ),
  );
  assert.deepEqual(results.map((r) => r.statusCode).sort(), [201, 409]);
  const id = results.find((r) => r.statusCode === 201)!.json().id;
  assert.equal(
    (
      await app.inject({
        method: "PATCH",
        url: `/api/sponsorships/${id}/`,
        headers: b,
        payload: { status: "accepted" },
      })
    ).statusCode,
    403,
  );
  assert.equal(
    (
      await app.inject({
        method: "PATCH",
        url: `/api/sponsorships/${id}/`,
        headers: a,
        payload: { status: "accepted" },
      })
    ).statusCode,
    200,
  );
  assert.equal(
    (
      await app.inject({
        method: "PATCH",
        url: `/api/sponsorships/${id}/`,
        headers: a,
        payload: { status: "declined" },
      })
    ).statusCode,
    409,
  );
  assert.equal(
    (
      await app.inject({ method: "GET", url: "/api/sponsorships/", headers: b })
    ).json().accepted_count,
    1,
  );
});

test("a realistic image within the 2 MiB limit uploads without regex stack failures", async (t) => {
  const { app } = await setup(t);
  const headers = await login(app);
  const bytes = Buffer.concat([
    Buffer.from([137, 80, 78, 71, 13, 10, 26, 10]),
    Buffer.alloc(512 * 1024),
  ]);
  const response = await app.inject({
    method: "POST",
    url: "/api/media/",
    headers,
    payload: {
      filename: "large.png",
      content_type: "image/png",
      content_base64: bytes.toString("base64"),
    },
  });
  assert.equal(response.statusCode, 201, response.body);
  assert.equal(response.json().size, bytes.length);
});

test("inherited object names are rejected as listing categories", async (t) => {
  const { app } = await setup(t);
  const headers = await login(app);
  for (const category of ["constructor", "toString", "__proto__"]) {
    for (const attributes of [{}, { bedrooms: 1 }]) {
      const response = await app.inject({
        method: "POST",
        url: "/api/listings/",
        headers,
        payload: listingPayload(category, { attributes }),
      });
      assert.equal(response.statusCode, 422, response.body);
    }
    const response = await app.inject({
      method: "GET",
      url:
        "/api/listings/?category_id=" +
        encodeURIComponent(category) +
        "&filters=" +
        encodeURIComponent(JSON.stringify({ bedrooms: 1 })),
      headers,
    });
    assert.equal(response.statusCode, 422, response.body);
  }
});
