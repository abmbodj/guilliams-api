for (const category of Object.keys(CATEGORY_FIELDS))
  test(`category ${category}: create, publish, detail and search`, async (t) => {
    const { app } = await setup(t);
    const headers = await login(app);
    const r = await app.inject({
      method: "POST",
      url: "/api/listings/",
      headers,
      payload: listingPayload(category),
    });
    assert.equal(r.statusCode, 201, r.body);
    const id = r.json().id;
    assert.equal(
      (
        await app.inject({
          method: "POST",
          url: `/api/listings/${id}/publish/`,
          headers,
        })
      ).json().status,
      "active",
    );
    assert.equal(
      (
        await app.inject({
          method: "GET",
          url: `/api/listings/${id}/`,
          headers,
        })
      ).json().category_id,
      category,
    );
    const result = await app.inject({
      method: "GET",
      url: `/api/listings/?category_id=${category}`,
      headers,
    });
    assert.equal(result.statusCode, 200, result.body);
    assert.ok(result.json().total >= 1);
  });

test("all OpenAPI operations are registered and optional authentication is documented", async (t) => {
  const { app } = await setup(t);
  const expected = new Set<string>();
  for (const [path, item] of Object.entries(specification.paths))
    for (const method of Object.keys(item as object))
      if (["get", "post", "put", "patch", "delete"].includes(method))
        expected.add(`${method.toUpperCase()} ${path}`);
  assert.equal(expected.size, 52);
  assert.deepEqual(app.operations, expected);
  assert.deepEqual(
    (await app.inject({ method: "GET", url: "/openapi.json" })).json(),
    specification,
  );
  for (const path of [
    "/api/auth/challenges/",
    "/api/auth/verify/",
    "/api/auth/challenges/{challenge_id}/resend/",
  ])
    assert.ok(
      specification.paths[path].post.security.some(
        (s: object) => !Object.keys(s).length,
      ),
    );
  const html = await app.inject({ method: "GET", url: "/docs" });
  assert.equal(html.statusCode, 200);
  assert.ok(!html.body.includes("cdn.jsdelivr"));
  assert.equal(
    (
      await app.inject({
        method: "GET",
        url: "/docs-assets/swagger-ui-bundle.js",
      })
    ).statusCode,
    200,
  );
});

test("persistence, foreign keys, and restart do not re-seed or overwrite user data", async (t) => {
  const { app, dbPath } = await setup(t);
  const headers = await login(app);
  const id = (
    await app.inject({
      method: "POST",
      url: "/api/listings/",
      headers,
      payload: listingPayload(),
    })
  ).json().id;
  const before = app.store.one("SELECT count(*) AS n FROM users")!.n;
  const other = createApp({ dbPath });
  t.after(() => other.close());
  await other.ready();
  const h = await login(other);
  assert.equal(
    (
      await other.inject({
        method: "GET",
        url: `/api/listings/${id}/`,
        headers: h,
      })
    ).json().title,
    "Test chair",
  );
  assert.equal(other.store.one("SELECT count(*) AS n FROM users")!.n, before);
  assert.deepEqual(other.store.all("PRAGMA foreign_key_check"), []);
  assert.equal(
    other.store.one("PRAGMA integrity_check")!.integrity_check,
    "ok",
  );
});

test("legacy Python SQLite password hashes, sessions and profiles remain compatible", async (t) => {
  const dir = mkdtempSync(join(tmpdir(), "guilliams-legacy-")),
    dbPath = join(dir, "legacy.sqlite3");
  const legacy = new DatabaseSync(dbPath);
  legacy.exec(
    readFileSync(new URL("../src/schema.sql", import.meta.url), "utf8"),
  );
  legacy.prepare("INSERT INTO cities VALUES (?,?)").run("london", "London");
  // Golden scrypt and token hashes generated by the original Python implementation.
  const hash =
    "00112233445566778899aabbccddeeff:4577f7877496087f9bff41641cc2cfe9c2922ad837f8ebd87ed6c23a5470201d9b91eb2bec5ae96b0763394a34544a3e081fb11d925f6cd109cbd5e9d0d3e413";
  legacy
    .prepare(
      "INSERT INTO users(id,username,password_hash,first_name,city_id,created_at) VALUES (?,?,?,?,?,?)",
    )
    .run("legacy", "LegacyUser", hash, "Original", "london", 1800000000);
  legacy
    .prepare("INSERT INTO sessions VALUES (?,?,?)")
    .run(
      "3fa70395d4ca9249d2fcd6967c0bf95dde7d65778b698ec8bcd59edd43729550",
      "legacy",
      1800086400,
    );
  legacy.close();
  const app = createApp({ dbPath, clock: () => 1800000000 });
  t.after(async () => {
    await app.close();
    rmSync(dir, { recursive: true, force: true });
  });
  await app.ready();
  const user = await app.inject({
    method: "GET",
    url: "/api/me/",
    headers: { authorization: "Bearer legacy-session" },
  });
  assert.equal(user.statusCode, 200, user.body);
  assert.equal(user.json().first_name, "Original");
  const signedIn = await app.inject({
    method: "POST",
    url: "/api/login/",
    payload: { username: "legacyuser", password: "LegacyPass123!" },
  });
  assert.equal(signedIn.statusCode, 200, signedIn.body);
  assert.equal(signedIn.json().user.id, "legacy");
  assert.equal(app.store.one("SELECT count(*) AS n FROM users")!.n, 1);
});

